"""Safely model fleet consequences of selected EmuOCPP findings.

This dependency-free demo is inspired by Boussaha et al., *EmuOCPP:
Effective and Scalable OCPP Security and Privacy Testing* (VehicleSec 2025).
It compares a benign charging-station-management-system (CSMS) registry with
three paper-motivated cases: duplicate charging-station identifiers, the
paper's M4 security-profile downgrade, and its D1 resource-exhaustion attack.

The implementation is intentionally a deterministic state-machine model.  It
does not emit OCPP messages, open attacker sockets, manipulate certificates,
perform neighbor-discovery/ARP spoofing, or contain code that can exploit a
real charger or CSMS.  The false ``Unavailable`` reports layered onto M4 and
the discrete ``BootNotification`` queue, processing capacity, backlog
threshold, and recovery rule used to illustrate D1 are explicit tutorial
assumptions, not protocol-faithful reproductions or measurements reported by
EmuOCPP.  All values are generated by this state model.  Taxi wait, downtime,
failed charging attempts, and passenger service are METS-R operational-impact
extensions; they were not measured by EmuOCPP.

Paper: https://www.usenix.org/system/files/vehiclesec25-boussaha.pdf
Authors' code: https://github.com/vfg27/EmuOCPP
"""

