def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run a safe EmuOCPP consequence abstraction and EV-taxi service model."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--seed", type=int, default=2504)
    parser.add_argument(
        "--duration-minutes",
        "--duration",
        dest="duration_minutes",
        type=int,
        default=120,
    )
    parser.add_argument(
        "--fleet-size", "--fleet", dest="fleet_size", type=int, default=24
    )
    parser.add_argument(
        "--station-count",
        "--stations",
        dest="station_count",
        type=int,
        default=4,
    )
    parser.add_argument(
        "--ports-per-station",
        "--ports",
        dest="ports_per_station",
        type=int,
        default=2,
    )
    parser.add_argument(
        "--attack-start-minute",
        "--attack-start",
        dest="attack_start_minute",
        type=int,
        help="First minute in the half-open attack window; default is 10%% of duration.",
    )
    parser.add_argument(
        "--attack-end-minute",
        "--attack-end",
        dest="attack_end_minute",
        type=int,
        help="Minute after the half-open attack window; default is 65%% of duration.",
    )
    parser.add_argument(
        "--duplicate-policy",
        "--policy",
        dest="duplicate_policy",
        choices=("last-wins", "keep-both", "reject-new"),
        default="last-wins",
        help="Abstract CSMS behavior when a duplicate charging-station ID boots.",
    )
    parser.add_argument(
        "--target-count",
        type=int,
        help="Stations affected in impersonation/downgrade scenarios; default is half.",
    )
    parser.add_argument(
        "--request-rate",
        type=float,
        help="Passenger requests per minute; default is fleet_size / 18.",
    )
    parser.add_argument("--flood-rate", type=int, default=24)
    parser.add_argument("--boot-processing-capacity", type=int, default=8)
    parser.add_argument("--dos-backlog-threshold", type=int, default=16)
    parser.add_argument("--status-interval-minutes", type=int, default=5)
    parser.add_argument("--retry-minutes", type=int, default=3)
    parser.add_argument("--charge-trigger-kwh", type=float, default=15.0)
    parser.add_argument("--charge-target-kwh", type=float, default=48.0)
    parser.add_argument("--charge-rate-kwh-per-minute", type=float, default=0.75)
    parser.add_argument(
        "--output-dir",
        "--output",
        dest="output_dir",
        default=str(
            _REPO_ROOT / "output" / "security_demos" / "emuocpp_consequences"
        ),
    )
    parser.add_argument(
        "--serve", action="store_true", help="Serve the finished dashboard until Ctrl-C."
    )
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument(
        "--port", type=int, default=0, help="Dashboard port; 0 chooses a free port."
    )
    parser.add_argument("--open-browser", action="store_true")
    args = parser.parse_args(argv)

    if args.duration_minutes <= 0:
        parser.error("--duration-minutes must be positive")
    if args.fleet_size <= 0:
        parser.error("--fleet-size must be positive")
    if args.station_count <= 0:
        parser.error("--station-count must be positive")
    if args.ports_per_station <= 0:
        parser.error("--ports-per-station must be positive")
    if args.attack_start_minute is None:
        args.attack_start_minute = max(1, int(round(args.duration_minutes * 0.10)))
    if args.attack_end_minute is None:
        args.attack_end_minute = max(
            args.attack_start_minute + 1,
            int(round(args.duration_minutes * 0.65)),
        )
    if not (
        0 <= args.attack_start_minute < args.attack_end_minute <= args.duration_minutes
    ):
        parser.error(
            "attack window must satisfy 0 <= start < end <= duration-minutes"
        )
    if args.target_count is None:
        args.target_count = max(1, args.station_count // 2)
    if not 1 <= args.target_count <= args.station_count:
        parser.error("--target-count must be between 1 and station-count")
    if args.request_rate is None:
        args.request_rate = args.fleet_size / 18.0
    for name in (
        "request_rate",
        "charge_trigger_kwh",
        "charge_target_kwh",
        "charge_rate_kwh_per_minute",
    ):
        if not math.isfinite(getattr(args, name)):
            parser.error(f"--{name.replace('_', '-')} must be finite")
    if args.request_rate < 0.0:
        parser.error("--request-rate cannot be negative")
    for name in (
        "flood_rate",
        "boot_processing_capacity",
        "dos_backlog_threshold",
        "status_interval_minutes",
        "retry_minutes",
    ):
        if getattr(args, name) <= 0:
            parser.error(f"--{name.replace('_', '-')} must be positive")
    if not 0.0 < args.charge_trigger_kwh < args.charge_target_kwh:
        parser.error("charge trigger must be positive and below charge target")
    if args.charge_rate_kwh_per_minute <= 0.0:
        parser.error("--charge-rate-kwh-per-minute must be positive")
    if not 0 <= args.port <= 65535:
        parser.error("--port must be between 0 and 65535")
    return args


def main(argv: Sequence[str] | None = None) -> int:
    return run(parse_args(argv))


if __name__ == "__main__":
    raise SystemExit(main())
